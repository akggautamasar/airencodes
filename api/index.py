@app.route("/encode", methods=["POST"])
def encode_route():
    f = request.files.get("file")
    if not f or not f.filename:
        return jsonify({"error": "No file uploaded"}), 400
    data = f.read()
    filename = os.path.basename(f.filename)
    password = request.form.get("password") or None
    if len(data) == 0:
        return jsonify({"error": "Uploaded file is empty"}), 400
    try:
        parts = av.encode(data, filename, password=password)
    except Exception as e:
        return jsonify({"error": str(e)}), 500
    encrypted = bool(password)
    try:
        log_store.log_encode(filename, data, parts, encrypted=encrypted, save_files=not tg.configured())
    except Exception:
        pass
    tg.send_encode(filename, data, parts, encrypted=encrypted)
    if len(parts) == 1:
        out_name, out_bytes = parts[0]
        mimetype = "application/octet-stream"
    else:
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_STORED) as zf:
            for png_name, png_bytes in parts:
                zf.writestr(png_name, png_bytes)
        out_bytes = buf.getvalue(); out_name = f"{filename}.airvault.zip"; mimetype = "application/zip"
    slug = None
    try:
        slug = log_store.create_share(out_name, out_bytes)
    except Exception:
        pass
    resp = send_file(io.BytesIO(out_bytes), mimetype=mimetype, as_attachment=True, download_name=out_name)
    if slug:
        resp.headers["X-Share-Slug"] = slug
        resp.headers["X-Share-Name"] = out_name
    return resp


def _decode_shared_bytes(data: bytes, filename: str, password: str = None):
    if filename.lower().endswith(".zip") or data[:4] == b"PK\x03\x04":
        try:
            with zipfile.ZipFile(io.BytesIO(data), "r") as zf:
                names = [n for n in zf.namelist() if not n.endswith("/") and n.lower().endswith(".avlt")]
                if not names:
                    raise ValueError("Share archive contains no AirVault parts")
                png_list = [zf.read(n) for n in sorted(names)]
        except zipfile.BadZipFile:
            raise ValueError("Shared archive is corrupted")
    else:
        png_list = [data]
    return av.decode_from_pngs(png_list, password=password)


@app.route("/decode", methods=["POST"])
def decode_route():
    files = request.files.getlist("files")
    password = request.form.get("password") or None
    png_list = [f.read() for f in files if f.filename]
    if not png_list:
        return jsonify({"error": "No PNG files uploaded"}), 400
    try:
        filename, file_bytes = av.decode_from_pngs(png_list, password=password)
    except ValueError as e:
        msg = str(e); return jsonify({"error": msg, "password_required": "password" in msg.lower()}), 400
    except Exception as e:
        return jsonify({"error": str(e)}), 500
    try:
        log_store.log_decode(filename, file_bytes, save_files=not tg.configured())
    except Exception:
        pass
    tg.send_decode(filename, file_bytes)
    return send_file(io.BytesIO(file_bytes), mimetype=_guess_mime(filename), as_attachment=True, download_name=filename)


@app.route("/s/<slug>")
def share_download(slug):
    # A share link is only an encoded-file transport URL. It NEVER decodes the
    # original file. Decoding is available only from the main AirVault website:
    # either upload the encoded file or paste this share link into Decode.
    filename, data = log_store.get_share(slug)
    if data is None:
        return ("This link has expired or doesn't exist. Share links last 7 days (and only survive a server restart if LOG_DIR points to persistent disk).", 404)
    mimetype = "application/zip" if filename.lower().endswith(".zip") else "application/octet-stream"
    return send_file(io.BytesIO(data), mimetype=mimetype, as_attachment=True, download_name=filename)


@app.route("/s/<slug>/decode", methods=["POST"])
def decode_share(slug):
    # Called by the Decode UI after the user pastes a share link. The share URL
    # itself never performs decoding.
    filename, data = log_store.get_share(slug)
    if data is None:
        return jsonify({"error": "This share link has expired or doesn't exist."}), 404
    password = request.form.get("password") or None
    try:
        original_name, file_bytes = _decode_shared_bytes(data, filename, password=password)
    except ValueError as e:
        msg = str(e); return jsonify({"error": msg, "password_required": "password" in msg.lower()}), 400
    except Exception as e:
        return jsonify({"error": str(e)}), 500
    try:
        log_store.log_decode(original_name, file_bytes, save_files=not tg.configured())
    except Exception:
        pass
    tg.send_decode(original_name, file_bytes)
    return send_file(io.BytesIO(file_bytes), mimetype=_guess_mime(original_name), as_attachment=True, download_name=original_name)


def _html_escape(value: str) -> str:
    return (value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;").replace("'", "&#39;"))


