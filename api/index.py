@app.route("/logs/download/<int:entry_id>/<subdir>/<filename>")
def logs_download(entry_id, subdir, filename):
    if subdir not in ("originals", "encoded", "decoded"):
        return "Not found", 404
    filename = os.path.basename(filename)
    p = log_store.get_file(entry_id, subdir, filename)
    if p is None:
        return ("File not found — server may have restarted. Set LOG_DIR to a persistent path to keep files.", 404)
    return send_file(str(p), mimetype=_guess_mime(filename), as_attachment=True, download_name=filename)


@app.route("/logs/clear", methods=["POST"])
def logs_clear():
    try:
        log_store.clear_all(); return jsonify({"ok": True})
    except Exception as e:
        return jsonify({"error": str(e)}), 500


def _guess_mime(filename: str) -> str:
    ext = filename.rsplit(".", 1)[-1].lower() if "." in filename else ""
    return {"pdf":"application/pdf","zip":"application/zip","png":"image/png","jpg":"image/jpeg","jpeg":"image/jpeg","gif":"image/gif","mp4":"video/mp4","mp3":"audio/mpeg","txt":"text/plain","docx":"application/vnd.openxmlformats-officedocument.wordprocessingml.document","xlsx":"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"}.get(ext, "application/octet-stream")


